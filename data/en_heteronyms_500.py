def build_500_pairs():
    """Build 500 unique heteronym injection pairs.

    For each of 50 words:
      For each of 5 reading_a contexts: pair (text=ctx, ref=reading_b.contexts[0]) = a_to_b direction
      For each of 5 reading_b contexts: pair (text=ctx, ref=reading_a.contexts[0]) = b_to_a direction

    Total: 50 words × 10 source contexts = 500 pairs.
    """
    pairs = []
    for entry in EN_HETERONYMS_50:
        w = entry["word"]
        ra_ctxs = entry["reading_a"]["contexts"]
        rb_ctxs = entry["reading_b"]["contexts"]
        assert len(ra_ctxs) == 5 and len(rb_ctxs) == 5, f"{w}: need 5 contexts per reading"
        # Direction A→B
        for ctx in ra_ctxs:
            pairs.append({
                "word_a": w, "word_b": w,
                "text_a": ctx, "text_b": rb_ctxs[0],
                "direction": "a_to_b",
                "reading_a_label": entry["reading_a"]["label"],
                "reading_b_label": entry["reading_b"]["label"],
            })
        # Direction B→A
        for ctx in rb_ctxs:
            pairs.append({
                "word_a": w, "word_b": w,
                "text_a": ctx, "text_b": ra_ctxs[0],
                "direction": "b_to_a",
                "reading_a_label": entry["reading_a"]["label"],
                "reading_b_label": entry["reading_b"]["label"],
            })
    assert len(pairs) == 500, f"Expected 500, got {len(pairs)}"
    return pairs


