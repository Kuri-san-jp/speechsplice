def build_300_pairs():
    """Return exactly 300 ZH polyphone evaluation pairs."""
    pairs = []
    pair_idx = 0
    for char, label_a, ctxs_a, label_b, ctxs_b in POLYPHONES:
        for text_a in ctxs_a:
            for text_b in ctxs_b:
                pairs.append({
                    "word_a": char,
                    "word_b": char,
                    "text_a": text_a,
                    "text_b": text_b,
                    "direction": "a_to_b",
                    "reading_a_label": label_a,
                    "reading_b_label": label_b,
                    "lang": "zh",
                    "pair_idx": pair_idx,
                })
                pair_idx += 1
    return pairs[:300]


