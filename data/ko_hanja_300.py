def build_300_pairs():
    """Return exactly 300 KO Hanja polyphone evaluation pairs."""
    pairs = []
    pair_idx = 0
    for char, label_a, ctxs_a, label_b, ctxs_b in HANJA_POLYPHONES:
        for text_a in ctxs_a:
            for text_b in ctxs_b:
                pairs.append({
                    "word_a": char,
                    "word_b": char,
                    "text_a": text_a,
                    "text_b": text_b,
                    "direction": "a_to_b",
                    "reading_a_label": label_a,
                    "reading_b_label": label_b,
                    "lang": "ko",
                    "pair_idx": pair_idx,
                })
                pair_idx += 1
    return pairs[:300]


if __name__ == "__main__":
    pairs = build_300_pairs()
    print(f"Total KO Hanja pairs: {len(pairs)}")
    print(f"Unique characters: {len(set(p['word_a'] for p in pairs))}")
